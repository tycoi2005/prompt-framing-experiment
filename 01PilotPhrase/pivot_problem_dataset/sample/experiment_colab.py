import requests, time

def call_ollama(model, system_prompt, user_prompt, max_tokens=4096, temperature=0.7):
    """Call Ollama API and return (response_text, metadata)."""
    start = time.time()
    try:
        r = requests.post("http://localhost:11434/api/generate", json={
            "model": model, "prompt": user_prompt, "system": system_prompt,
            "stream": False, "options": {"temperature": temperature, "num_predict": max_tokens}
        }, timeout=300)
        r.raise_for_status()
        data = r.json()
        return data.get("response", ""), {
            "duration": time.time() - start,
            "prompt_tokens": data.get("prompt_eval_count", 0),
            "completion_tokens": data.get("eval_count", 0),
            "success": True, "error": ""
        }
    except Exception as e:
        return "", {"duration": time.time() - start, "prompt_tokens": 0,
                    "completion_tokens": 0, "success": False, "error": str(e)}

