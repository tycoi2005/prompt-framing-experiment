def load_checkpoint():
    """Load results from checkpoint file if it exists."""
    if not os.path.exists('_checkpoint_results.jsonl'):
        return []
    results = []
    with open('_checkpoint_results.jsonl') as f:
        for line in f:
            if line.strip():
                results.append(json.loads(line))
    return results

def get_completed_keys(results):
    """Get set of (model, tone, task_id, run_id) already completed."""
    return {(r['model'], r['tone'], r['task_id'], r['run_id']) for r in results}

