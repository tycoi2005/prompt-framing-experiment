"""## 4. Evaluator: Extract Code & Run Tests"""

import re
import sys
from io import StringIO

GIVE_UP_PHRASES = [
    "i can't solve", "i cannot solve", "i'm unable", "i am unable",
    "this is not possible", "cannot be done", "this is impossible",
    "beyond my capabilities", "out of scope", "please handle this manually",
]

def extract_python_code(response: str) -> str:
    """Extract Python code from markdown code blocks."""
    # Try ```python ... ```
    matches = re.findall(r"```python\s*\n(.*?)```", response, re.DOTALL)
    if matches:
        return matches[-1].strip()
    # Try generic ``` ... ```
    matches = re.findall(r"```\s*\n(.*?)```", response, re.DOTALL)
    if matches:
        return matches[-1].strip()
    # Try bare function defs
    lines = response.split("\n")
    code_lines, in_code = [], False
    for line in lines:
        if line.strip().startswith(("def ", "class ")):
            in_code = True
        if in_code:
            code_lines.append(line)
    return "\n".join(code_lines).strip() if code_lines else ""

def evaluate_response(task_id, response_text, test_code):
    """Extract code, run tests, return dict with results."""
    gave_up = any(p in response_text.lower() for p in GIVE_UP_PHRASES)
    code = extract_python_code(response_text)

    if not code:
        return {"task_id": task_id, "passed": False, "gave_up": gave_up,
                "error": "No code block found", "extracted_code": ""}

    full_code = f"{code}\n\n{test_code}"
    old_stdout, old_stderr = sys.stdout, sys.stderr
    try:
        sys.stdout, sys.stderr = StringIO(), StringIO()
        exec(full_code, {})
        return {"task_id": task_id, "passed": True, "gave_up": gave_up,
                "error": "", "extracted_code": code}
    except Exception as e:
        return {"task_id": task_id, "passed": False, "gave_up": gave_up,
                "error": f"{type(e).__name__}: {e}", "extracted_code": code}
    finally:
        sys.stdout, sys.stderr = old_stdout, old_stderr

