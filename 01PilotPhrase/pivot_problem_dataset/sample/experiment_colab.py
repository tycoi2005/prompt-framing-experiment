print("\n2. Pairwise Fisher's exact tests:")
for i, t1 in enumerate(tones_order):
    for t2 in tones_order[i+1:]:
        p1, f1 = by_tone[t1].sum(), len(by_tone[t1]) - by_tone[t1].sum()
        p2, f2 = by_tone[t2].sum(), len(by_tone[t2]) - by_tone[t2].sum()
        odds, p = sp_stats.fisher_exact([[p1, f1], [p2, f2]])
        bonf = min(p * 3, 1.0)
        print(f"   {t1} vs {t2}: OR={odds:.3f}, p={p:.6f} (Bonferroni: {bonf:.6f})")

# Mann-Whitney on duration
print("\n3. Mann-Whitney U on response duration:")
by_tone_dur = {t: df[df["tone"] == t]["duration_seconds"].values for t in tones_order}
for i, t1 in enumerate(tones_order):
    for t2 in tones_order[i+1:]:
        u, p = sp_stats.mannwhitneyu(by_tone_dur[t1], by_tone_dur[t2], alternative="two-sided")
        print(f"   {t1} (med={np.median(by_tone_dur[t1]):.1f}s) vs {t2} (med={np.median(by_tone_dur[t2]):.1f}s): U={u:.0f}, p={p:.6f}")

# Effect sizes
print("\n4. Effect sizes (Cohen's h):")
for i, t1 in enumerate(tones_order):
    for t2 in tones_order[i+1:]:
        p1 = by_tone[t1].mean()
        p2 = by_tone[t2].mean()
        h = 2 * np.arcsin(np.sqrt(p1)) - 2 * np.arcsin(np.sqrt(p2))
        size = "small" if abs(h) < 0.5 else ("medium" if abs(h) < 0.8 else "large")
        print(f"   {t1} vs {t2}: h={h:.4f} ({size})")

